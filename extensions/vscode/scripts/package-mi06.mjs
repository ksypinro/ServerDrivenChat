// Package the MI-06 companion while copying the accepted MI-04 native archive unchanged.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { readZipEntries, writeZip } from './vsix.mjs';
const root = fileURLToPath(new URL('../../../', import.meta.url));
const ext = join(root, 'extensions/vscode');
const out = join(ext, 'dist/mi06-candidate');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const accepted = JSON.parse(await readFile(join(root, 'evidence/MI04/artifact-manifest.json'), 'utf8'));
const nativeName = 'cline-4.1.2206-mi04.1.vsix';
const native = await readFile(join(ext, 'dist/mi04-candidate', nativeName));
if (hash(native) !== accepted.artifacts.find(x => x.file === nativeName)?.sha256) throw Error('Accepted native archive does not match MI-04 evidence');
const source = JSON.parse(await readFile(join(ext, 'package.json'), 'utf8'));
if (source.version !== '0.10.0') throw Error('Expected MI-06 companion 0.10.0');
const companion = readZipEntries(await readFile(join(ext, 'dist/mi03-candidate/sdc-cline-bridge-0.8.0-mi03.1.vsix'))).entries;
const manifest = JSON.parse(companion.get('extension/package.json'));
manifest.version = source.version; manifest.contributes = source.contributes;
const bundle = await readFile(join(ext, 'dist/extension.cjs'));
companion.set('extension/package.json', Buffer.from(JSON.stringify(manifest, null, 2) + '\n'));
companion.set('extension/dist/extension.cjs', bundle);
companion.set('extension/README.md', Buffer.from('# MI-06 candidate\n\nUnsigned command-retention recovery candidate.\n'));
companion.set('extension.vsixmanifest', Buffer.from(companion.get('extension.vsixmanifest').toString().replace(/Version="0\.8\.0"/g, 'Version="0.10.0"')));
const companionName = 'sdc-cline-bridge-0.10.0-mi06.2.vsix';
const files = [{file:nativeName,bytes:native},{file:companionName,bytes:writeZip([...companion])}];
await mkdir(out,{recursive:true}); await mkdir(join(root,'evidence/MI06'),{recursive:true});
for (const f of files) await writeFile(join(out,f.file),f.bytes);
const record={milestone:'MI-06',status:'unsigned-candidate',nativePin:accepted.nativePin,nativeApi:accepted.nativeApi,companion:source.version,companionBundleSha256:hash(bundle),artifacts:files.map(f=>({file:f.file,sha256:hash(f.bytes)})),publication:'none',serverImage:{tag:'sdc-server:mi06-candidate.2',imageId:execFileSync('docker',['image','inspect','--format','{{.Id}}','sdc-server:mi06-candidate.2'],{encoding:'utf8'}).trim()},migrations:await Promise.all(['011_command_retention.sql','012_command_turn_ownership.sql'].map(async file=>({file,sha256:hash(await readFile(join(root,'server/migrations',file)))})))};
await writeFile(join(root,'evidence/MI06/artifact-manifest.json'),JSON.stringify(record,null,2)+'\n');
console.log(JSON.stringify(record,null,2));
